#!/usr/bin/env python3
"""Verify/refresh the pinned TS12 payment schema. Never used during wallet transactions."""
import argparse
import hashlib
import json
import re
import urllib.parse
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MANIFEST = ROOT / "scripts/ts12-payment-schema.json"
OUTPUT = ROOT / "waltid-libraries/protocols/waltid-openid4vp/src/commonMain/kotlin/id/walt/verifier/openid/transactiondata/Ts12PaymentSchema.kt"
REPOSITORY = "eu-digital-identity-wallet/eudi-doc-standards-and-technical-specifications"
KOTLIN_DOLLAR = "${'$'}"
SOURCE_PATH = "docs/technical-specifications/api/ts12-urn-eudi-sca-payment-1-data-model.json"


def read_url(url):
    with urllib.request.urlopen(urllib.request.Request(url, headers={"User-Agent": "waltid-ts12-schema-check"}), timeout=30) as response:
        return response.read()


def resolve(ref):
    return json.loads(read_url(f"https://api.github.com/repos/{REPOSITORY}/commits/{urllib.parse.quote(ref, safe='')}"))["sha"]


def digest(data):
    return hashlib.sha256(data).hexdigest()


def generate(data, commit):
    source = data.decode("utf-8").replace("$", KOTLIN_DOLLAR)
    return f'''package id.walt.verifier.openid.transactiondata

import kotlinx.serialization.json.Json
import kotlinx.serialization.json.JsonObject
import kotlinx.serialization.json.jsonObject

/**
 * Generated by scripts/sync-ts12-payment-schema.py --update --ref <commit>; do not edit.
 * EUDI TS12 payment schema, © European Union, CC BY 4.0.
 * https://creativecommons.org/licenses/by/4.0/
 * Source: https://github.com/{REPOSITORY}/blob/{commit}/{SOURCE_PATH}
 * TS12 prose and stricter product restrictions are checked separately.
 */
internal object Ts12PaymentSchema {{
    const val SOURCE_COMMIT: String = "{commit}"
    const val SOURCE_SHA256: String = "{digest(data)}"
    val value: JsonObject by lazy {{ Json.parseToJsonElement(DEFINITION).jsonObject }}
    private const val DEFINITION = """
{source}"""
}}
'''


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    action = parser.add_mutually_exclusive_group(required=True)
    action.add_argument("--check", action="store_true", help="Offline: verify the generated copy against its pin and checksum")
    action.add_argument("--check-upstream", action="store_true", help="Read upstream main and report schema drift; writes nothing")
    action.add_argument("--update", action="store_true", help="Refresh the snapshot from an explicitly selected upstream revision")
    parser.add_argument("--ref", help="Upstream commit/ref, required for --update")
    args = parser.parse_args()
    manifest = json.loads(MANIFEST.read_text())
    text = OUTPUT.read_text()
    match = re.search(r'private const val DEFINITION = """\n(.*?)"""', text, re.S)
    if not match:
        raise SystemExit("Cannot locate generated schema definition")
    local = match.group(1).replace(KOTLIN_DOLLAR, "$").encode("utf-8")
    json.loads(local)
    if args.check or args.check_upstream:
        if digest(local) != manifest["sourceSha256"] or text != generate(local, manifest["sourceCommit"]):
            raise SystemExit("TS12 schema snapshot or generated wrapper differs from its source pin; review or regenerate it")
        if args.check:
            print(f"TS12 schema matches pin {manifest['sourceCommit']} ({manifest['sourceSha256']})")
            return
        url = f"https://raw.githubusercontent.com/{REPOSITORY}/main/{SOURCE_PATH}"
        remote = read_url(url)  # One request; no API token, commit lookup, cache fallback or runtime dependency.
        json.loads(remote)
        if digest(remote) != manifest["sourceSha256"]:
            raise SystemExit(f"Upstream TS12 payment schema changed: {url}\nReview its history and update validation, metadata and tests, then run:\npython3 scripts/sync-ts12-payment-schema.py --update --ref <reviewed-commit>")
        print("Pinned TS12 payment schema matches upstream main")
        return
    if not args.ref:
        parser.error("--update requires an explicitly selected --ref")
    commit = resolve(args.ref)
    url = f"https://raw.githubusercontent.com/{REPOSITORY}/{commit}/{SOURCE_PATH}"
    remote = read_url(url)
    json.loads(remote)
    OUTPUT.write_text(generate(remote, commit))
    MANIFEST.write_text(json.dumps({"sourceCommit": commit, "sourceSha256": digest(remote), "sourceUrl": url}, indent=2) + "\n")
    print(f"Updated TS12 schema to {commit}. Review the diff and run shared, service and platform tests before release.")


if __name__ == "__main__":
    main()
