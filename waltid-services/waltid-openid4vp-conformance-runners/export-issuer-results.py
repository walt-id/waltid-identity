#!/usr/bin/env python3
"""Export the last IssuerConformanceTests run into a committable markdown snapshot.

Reads build/reports/openid-conformance/vci-issuer/{matrix.json,results.json} (written by
IssuerVariantReportWriter after `./run-issuer-conformance-local.sh`, or a direct
IssuerConformanceTests.runIssuerConformanceTests invocation) and writes a per-variant breakdown of
modules and their status to docs/VCI-ISSUER-RESULTS.md, so results are tracked in git instead of
only living in the gitignored build/ directory.

Unlike the verifier matrix, an issuer variant can have a matrix.json entry with no modules at all -
GENERATED (never selected to run), BLOCKED (local setup missing, e.g. no reachable auth server),
SUITE_INVALID (suite rejected the variant before creating a plan) or NOT_APPLICABLE (plan created
with no modules). Those are listed with an explanatory note instead of a module table.

Usage:
    ./export-issuer-results.py [--note "context for this run"]
"""

import argparse
import json
import subprocess
import sys
from datetime import datetime, timezone
from pathlib import Path

MODULE_ROOT = Path(__file__).resolve().parent
REPORT_DIR = MODULE_ROOT / "build/reports/openid-conformance/vci-issuer"
DEFAULT_OUTPUT = MODULE_ROOT / "docs/VCI-ISSUER-RESULTS.md"

MODULE_STATUS_EMOJI = {"PASSED": "✅", "FAILED": "❌"}
VARIANT_STATUS_EMOJI = {
    "PASSED": "✅",
    "FAILED": "❌",
    "BLOCKED": "🚧",
    "SUITE_INVALID": "⚠️",
    "NOT_APPLICABLE": "➖",
    "GENERATED": "⏭️",
}
VARIANT_STATUS_NOTE = {
    "BLOCKED": "required local setup is missing (e.g. an offer, login automation, mTLS material, or a reachable endpoint)",
    "SUITE_INVALID": "the suite rejected this variant before creating a plan",
    "NOT_APPLICABLE": "the suite created a plan with no modules",
    "GENERATED": "generated but not selected to run",
}


def git(*args: str) -> str | None:
    try:
        return subprocess.check_output(
            ["git", "-C", str(MODULE_ROOT), *args], text=True, stderr=subprocess.DEVNULL
        ).strip()
    except (subprocess.CalledProcessError, FileNotFoundError):
        return None


def load_json(path: Path) -> list[dict]:
    if not path.is_file():
        sys.exit(
            f"error: {path} not found - run the suite first:\n"
            "  cd waltid-services/waltid-openid4vp-conformance-runners\n"
            "  ./run-issuer-conformance-local.sh"
        )
    return json.loads(path.read_text())


def render(matrix: list[dict], results: list[dict], note: str | None) -> str:
    results_by_variant = {r["variantId"]: r for r in results}

    total_modules = sum(len(r.get("modules", [])) for r in results)
    passed_modules = sum(
        1 for r in results for m in r.get("modules", []) if m.get("result") == "PASSED"
    )
    failed_modules = total_modules - passed_modules
    variants_passed = sum(1 for v in matrix if v["status"] == "PASSED")

    branch = git("rev-parse", "--abbrev-ref", "HEAD") or "unknown"
    commit = git("rev-parse", "--short", "HEAD") or "unknown"
    dirty = bool(git("status", "--porcelain", "."))
    generated = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")

    lines = [
        "# VCI-Issuer Conformance Results",
        "",
        "Auto-generated by `export-issuer-results.py` - do not hand-edit, rerun the script instead.",
        "",
        f"- Generated: {generated}",
        f"- Branch: `{branch}` @ `{commit}`" + (" (module has uncommitted changes)" if dirty else ""),
    ]
    if note:
        lines.append(f"- Note: {note}")
    lines += [
        "",
        f"**Summary:** {variants_passed}/{len(matrix)} variants fully passed. "
        f"{passed_modules}/{total_modules} modules passed across the {len(results)} variant(s) that ran.",
        "",
    ]

    for entry in matrix:
        variant_id = entry["variantId"]
        status = entry["status"]
        emoji = VARIANT_STATUS_EMOJI.get(status, "?")
        result = results_by_variant.get(variant_id)
        modules = result.get("modules", []) if result else []

        axes = ", ".join(f"{k}={v}" for k, v in entry.get("variant", {}).items())
        lines.append(f"## {variant_id} {emoji} `{status}`")
        lines.append("")
        lines.append(f"_{axes}_")
        lines.append("")

        if modules:
            m_passed = sum(1 for m in modules if m.get("result") == "PASSED")
            lines.append(f"{m_passed}/{len(modules)} modules passed.")
            lines.append("")
            lines.append("| Module | Result | Log | Error |")
            lines.append("|---|---|---|---|")
            for m in modules:
                m_emoji = MODULE_STATUS_EMOJI.get(m.get("result"), "?")
                log_url = m.get("logUrl")
                log_cell = f"[log]({log_url})" if log_url else "-"
                error = (m.get("error") or "").replace("\n", " ").replace("|", "\\|")
                lines.append(f"| `{m['testModule']}` | {m_emoji} {m.get('result', '-')} | {log_cell} | {error} |")
        else:
            note_text = VARIANT_STATUS_NOTE.get(status, entry.get("error") or "no modules recorded")
            lines.append(f"No modules ran - {note_text}.")
            if entry.get("error"):
                lines.append(f"Error: `{entry['error']}`")

        lines.append("")

    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--report-dir", type=Path, default=REPORT_DIR, help="dir with matrix.json/results.json")
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT, help="markdown file to write")
    parser.add_argument("--note", help="one-line context for this run, e.g. what changed since the last export")
    args = parser.parse_args()

    matrix = load_json(args.report_dir / "matrix.json")
    results = load_json(args.report_dir / "results.json")
    markdown = render(matrix, results, args.note)

    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(markdown + "\n")
    print(f"Wrote {args.output}")


if __name__ == "__main__":
    main()
