/**
 * Shared mDL test fixture, so the DC API round trip and the cross-device mdoc test verify the same
 * issuer-signed credential and a DC API failure is attributable to the DC API path.
 *
 * [HOLDER_JWK] is the `deviceKey` embedded in every fixture MSO - `device_key_auth` fails if the two
 * drift apart - and its `kid` is that key's RFC 7638 thumbprint. [HOLDER_SERIALIZED_KEY] is the same key
 * in the envelope the crypto v1 `KeyManager` takes.
 *
 * ## Issuer
 *
 * The IACA and document signer are generated at build time by the `waltid.x509` plugin
 * (`mdl-fixture-iaca` and `mdl-fixture-ds` in this module's `build.gradle.kts`) and read from the
 * test classpath; the plugin regenerates them before they get close to expiring. Fixture mdocs are
 * signed with them at test time ([mdlFixtureCredential]), so no test depends on a calendar date.
 *
 * The document signer is a conformant ISO 18013-5 signer (`keyUsage:digitalSignature`, EKU
 * `1.0.18013.5.1.2`), unlike the deployed demo issuer's X.509 v1 signer, which is why `issuer_auth`
 * passes here.
 */
private object MdlFixtureResources {
    fun read(path: String): String = requireNotNull(javaClass.getResource("/mdl-fixture-ds/$path")) {
        "Missing mdl-fixture-ds/$path on the test classpath; it is generated by the generateX509Certificates task"
    }.readText()
}

/** The document signer certificate as base64 DER, the way `x5c` and `x5chain` carry it. */
internal val MDL_FIXTURE_X5C: String =
    MdlFixtureResources.read("certificate.pem").lineSequence().filterNot { it.startsWith("-----") }.joinToString("")

internal val MDL_FIXTURE_SIGNER_JWK: String =
    """{"type":"jwk","jwk":${MdlFixtureResources.read("public.jwk.json")}}"""

/** Private half of [MDL_FIXTURE_SIGNER_JWK], for tests that mint their own mdoc at runtime. */
internal val MDL_FIXTURE_SIGNER_PRIVATE_JWK: String =
    """{"type":"jwk","jwk":${MdlFixtureResources.read("private.jwk.json")}}"""

/** MSO validity of minted fixtures; within the document signer's remaining validity, as ISO 18013-5 requires. */
internal val MDL_FIXTURE_MSO_VALIDITY = 30.days

/**
 * [credentialData] - `docType` plus one object per namespace, as `MdocsCredential.credentialData`
 * holds it - as a wallet credential signed by the fixture document signer and bound to [HOLDER_JWK].
 */
internal fun mdlFixtureCredential(credentialData: String): MdocsCredential = runBlocking {
    val data = Json.decodeFromString<JsonObject>(credentialData)
    val docType = data.getValue("docType").jsonPrimitive.content
    val now = Clock.System.now()
    val issuerSigned = MdocIssuer.issueUniversal(
        issuerKey = restoreCrypto2Key(MdlFixtureResources.read("private.jwk.json"), "mdl-fixture-ds"),
        signatureAlgorithm = Cose.Algorithm.ES256,
        issuerCertificate = listOf(CoseCertificate(MDL_FIXTURE_X5C.decodeFromBase64())),
        holderKey = (KeyManager.resolveSerializedKey(HOLDER_SERIALIZED_KEY) as JWKKey).getPublicKey().getCosePublicKey(),
        docType = docType,
        data = MdocIssuer.MdocUniversalIssuanceData(
            data.filterValues { it is JsonObject }.mapValues { it.value as JsonObject }
        ),
        validFrom = now,
        validUntil = now + MDL_FIXTURE_MSO_VALIDITY,
    )
    MdocsCredential(
        credentialData = data,
        signed = coseCompliantCbor.encodeToHexString(Document(docType, issuerSigned)),
        docType = docType,
        signature = CoseCredentialSignature(
            x5cList = X5CList(listOf(X5CCertificateString(MDL_FIXTURE_X5C))),
            signerKey = DirectSerializedKey(KeyManager.resolveSerializedKey(MDL_FIXTURE_SIGNER_JWK)),
        ),
    )
}

private suspend fun restoreCrypto2Key(jwk: String, keyId: String): Key =
    CryptoRuntime(defaultSoftwareKeyProviders()).restore(
        EncodedKey.Jwk(BinaryData(jwk.encodeToByteArray()), privateMaterial = true)
            .toStoredSoftwareKey(id = KeyId(keyId), usages = setOf(KeyUsage.SIGN))
    )

internal const val HOLDER_JWK: String =
    """{
      "kty": "EC",
      "d": "QN9Y3k_3Hy2OV0C5Pmez_ObEXJKcXonnMg3xTpcLOAg",
      "crv": "P-256",
      "kid": "KmQ8TOSmhg1UV9nQfQaTQ5wwbHrEgOENvJ_3AlEriAw",
      "x": "eTT2WdzlmOWBItdgSmsqB1_BP69wfuwOe1IYvaY1WdI",
      "y": "wbOu3GP02JiOVIRQ_ufWLRNOmDB6seYAabCmsGBfr_4"
    }"""

/** [HOLDER_JWK] in the envelope `KeyManager.resolveSerializedKey` expects, for the crypto v1 callers. */
internal const val HOLDER_SERIALIZED_KEY: String =
    """{"type":"jwk","jwk":""" + HOLDER_JWK + "}"

/** Restores [HOLDER_JWK] as a Crypto2 signing key for mdoc device authentication. */
internal suspend fun restoreMdlHolderCrypto2Key(keyId: String): Key = restoreCrypto2Key(HOLDER_JWK, keyId)
